@dp.callback_query(F.data.startswith("opt_"))
async def handle_choice(callback: CallbackQuery):
    idx = int(callback.data.split("_")[1])
    player = get_player(callback.from_user.id)
    step = player["step"]
    data = QUEST_DATA[step]

    selected = data["options"][idx]

    # Обработка концовок на 50 шаге
    if "ending" in selected:
        if selected["ending"] == "good":
            fin_text = (
                "🏆 **ХОРОШАЯ КОНЦОВКА: Истинный Герой.**\n\n"
                "Ты запер створки бункера изнутри и повернул ключ детонации. Мощнейший подземный взрыв "
                "сжег первородный штамм и очистил город от скверны. Человечество спасено ценой твоей жизни!\n\n"
                "ИГРА ОКОНЧЕНА."
            )
        else:
            fin_text = (
                "💀 **ПЛОХАЯ КОНЦОВКА: Трагический эгоизм.**\n\n"
                "Ты поднялся в воздух на спасательном вертолете с вакциной. Но скрытый укус на запястье "
                "дал о себе знать на высоте 2000 метров. Глаза заволокло красным, рассудок угас... Вертолет рухнул на руины города.\n\n"
                "ИГРА ОКОНЧЕНА."
            )
        # Сброс прогресса после завершения
        player["step"] = 1
        await callback.message.answer(fin_text, parse_mode="Markdown")
        return

    # Правильный выбор
    if selected.get("correct"):
        player["step"] += 1
        await callback.message.answer("✅ **Ты выжил!** Двигаемся дальше...")
        await send_step_ui(callback.message.chat.id, callback.from_user.id)
    else:
        # Смерть игрока
        death_text = f"☠️ {selected.get('death')}\n\nПопробуешь снова с этого шага?"
        kb = InlineKeyboardMarkup(inline_keyboard=[
            [InlineKeyboardButton(text="🔁 Попробовать этот шаг снова", callback_data="retry_step")]
        ])
        await callback.message.answer(death_text, reply_markup=kb)

